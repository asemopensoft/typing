export type Language = "en" | "ar";
export type WordMode = "common" | "medium" | "code" | "quotes";

export function generateText(
  language: Language,
  mode: WordMode,
  wordCount = 50,
  weakChars: string[] = []
): string {
  if (mode === "quotes") {
    const pool = language === "en" ? EN_QUOTES : AR_QUOTES;
    return pool[Math.floor(Math.random() * pool.length)];
  }

  let pool: string[];
  if (language === "ar") {
    pool = mode === "medium" ? AR_MEDIUM_WORDS : AR_COMMON_WORDS;
  } else {
    if (mode === "code") pool = EN_CODE_WORDS;
    else if (mode === "medium") pool = EN_MEDIUM_WORDS;
    else pool = EN_COMMON_WORDS;
  }

  // If weak chars provided, boost words containing them
  if (weakChars.length > 0) {
    const boosted = pool.filter((w) =>
      weakChars.some((c) => w.includes(c))
    );
    if (boosted.length >= 5) {
      // Mix 60% boosted + 40% regular
      const words: string[] = [];
      for (let i = 0; i < wordCount; i++) {
        if (Math.random() < 0.6) {
          words.push(boosted[Math.floor(Math.random() * boosted.length)]);
        } else {
          words.push(pool[Math.floor(Math.random() * pool.length)]);
        }
      }
      return words.join(" ");
    }
  }

  const words: string[] = [];
  for (let i = 0; i < wordCount; i++) {
    words.push(pool[Math.floor(Math.random() * pool.length)]);
  }
  return words.join(" ");
}
